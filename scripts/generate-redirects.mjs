// Writes dist/_redirects after each build.
// Cloudflare Pages evaluates _redirects rules before static assets, so a bare
// /quiz/* catch-all would mask the prerendered edition pages and their
// per-edition Open Graph tags. Exact rules for each prerendered edition come
// first and proxy to their own static files, then the catch-all sends unknown
// edition numbers to the client-rendered shell.

import { readdirSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const distUrl = new URL('../dist/', import.meta.url);
const quizUrl = new URL('quiz/', distUrl);

const lines = [
  '# Generated by scripts/generate-redirects.mjs, do not edit by hand.',
  '# Exact rules keep prerendered editions serving their own HTML and OG tags.',
  '# The final rule serves the client-rendered shell for newer editions.',
];

if (existsSync(quizUrl)) {
  const editions = readdirSync(quizUrl, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && /^\d+$/.test(entry.name))
    .map((entry) => Number(entry.name))
    .sort((a, b) => a - b);
  for (const n of editions) {
    lines.push(`/quiz/${n} /quiz/${n}/ 200`);
    lines.push(`/quiz/${n}/ /quiz/${n}/ 200`);
  }
}

lines.push('/quiz/* /quiz/ 200');

writeFileSync(new URL('_redirects', distUrl), lines.join('\n') + '\n');
console.log(`Wrote ${fileURLToPath(new URL('_redirects', distUrl))}`);
